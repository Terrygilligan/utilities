// English text for namespaced keys (e.g. 'action.clear' -> 'Clear').
// Plain English keys never need an entry here — they are their own English text.
export const EN: Record<string, string> = {
  'db.clear': 'Clear',
  'receipt.clear': 'Clear',
  'csv.clear': 'Clear',
  'imgpdf.clear': 'Clear',
}

export function t(english: string, vars?: Record<string, string | number>): string {
  const str = LANG === 'en'
    ? EN[english] ?? english
    : dicts[LANG][english] ?? EN[english] ?? english
  return vars
    ? str.replace(/\{(\w+)\}/g, (match, key: string) =>
        Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match)
    : str
}
